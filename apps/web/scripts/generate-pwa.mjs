import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative, sep } from "node:path";

function readOption(name) {
  const option = `--${name}=`;
  const argument = process.argv.find((value) => value.startsWith(option));
  return argument?.slice(option.length);
}

function normalizeBase(base) {
  if (
    !base.startsWith("/") ||
    base.startsWith("//") ||
    !base.endsWith("/") ||
    base.includes("?") ||
    base.includes("#") ||
    base.split("/").some((segment) => segment === "." || segment === "..")
  ) {
    throw new Error(`Invalid PWA base: ${base}`);
  }
  return base;
}

const dist = resolve(process.cwd(), readOption("dist") ?? "dist");
const base = normalizeBase(readOption("base") ?? "/");
const isPagesBuild = process.argv.includes("--pages");
const ignored = new Set([
  "_headers",
  "sw.js",
  "version.json",
  "stockfish-smoke.html",
]);

async function filesAt(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const target = resolve(directory, entry.name);
      return entry.isDirectory() ? filesAt(target) : [target];
    }),
  );
  return files.flat();
}

const allFiles = await filesAt(dist);
const assets = (
  await Promise.all(
    allFiles.map(async (file) => {
      const path = relative(dist, file).split(sep).join("/");
      return { path, content: await readFile(file) };
    }),
  )
)
  .filter(({ path }) => !ignored.has(path))
  .sort((left, right) => left.path.localeCompare(right.path));

const fingerprint = createHash("sha256");
for (const asset of assets)
  fingerprint.update(asset.path).update("\0").update(asset.content);
const buildId = (
  process.env.BUILD_ID ||
  process.env.GIT_SHA ||
  fingerprint.digest("hex").slice(0, 12)
)
  .replace(/[^a-zA-Z0-9._-]/g, "-")
  .slice(0, 64);
const precache = assets.map(({ path }) => `${base}${path}`);

const version = JSON.stringify({ buildId, assets: precache }, null, 2) + "\n";
const indexPath = resolve(dist, "index.html");
const index = await readFile(indexPath, "utf8");
if (!index.includes("__CHESS_COACH_BUILD_ID__")) {
  throw new Error("Missing build-id placeholder in dist/index.html");
}
const worker = `/* Generated by scripts/generate-pwa.mjs. */
const BUILD_ID = ${JSON.stringify(buildId)};
const CACHE = "chess-coach-" + BUILD_ID;
const PRECACHE = ${JSON.stringify(precache)};
const sameOriginOk = (request, response) => new URL(request.url).origin === self.location.origin && response && response.status === 200;
self.addEventListener("install", (event) => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  const responses = await Promise.all(PRECACHE.map(async (path) => {
    const request = new Request(path, { cache: "reload" });
    const response = await fetch(request);
    if (!sameOriginOk(request, response)) throw new Error("Precache failed: " + path);
    return [request, response] ;
  }));
  await Promise.all(responses.map(([request, response]) => cache.put(request, response)));
})()));
self.addEventListener("message", (event) => { if (event.data?.type === "SKIP_WAITING") self.skipWaiting(); });
self.addEventListener("activate", (event) => event.waitUntil((async () => {
  await Promise.all((await caches.keys()).filter((key) => key.startsWith("chess-coach-") && key !== CACHE).map((key) => caches.delete(key)));
  await self.clients.claim();
})()));
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  const url = new URL(request.url);
  if (request.mode === "navigate") {
    event.respondWith(caches.open(CACHE).then(async (cache) => (await cache.match(${JSON.stringify(`${base}index.html`)})) || fetch(request)));
    return;
  }
  event.respondWith(caches.open(CACHE).then((cache) => cache.match(request).then((cached) => cached || fetch(request))));
});
`;
const manifestPath = resolve(dist, "manifest.webmanifest");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const baseManifestPath = (path) =>
  typeof path === "string" && path.startsWith("/")
    ? `${base}${path.slice(1)}`
    : path;
manifest.id = base;
manifest.scope = base;
manifest.start_url = base;
manifest.icons = manifest.icons?.map((icon) => ({
  ...icon,
  src: baseManifestPath(icon.src),
}));
await Promise.all([
  writeFile(indexPath, index.replaceAll("__CHESS_COACH_BUILD_ID__", buildId)),
  writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`),
  writeFile(resolve(dist, "version.json"), version),
  writeFile(resolve(dist, "sw.js"), worker),
  ...(isPagesBuild
    ? [
        writeFile(
          resolve(dist, "404.html"),
          index.replaceAll("__CHESS_COACH_BUILD_ID__", buildId),
        ),
        writeFile(resolve(dist, ".nojekyll"), ""),
      ]
    : []),
]);
